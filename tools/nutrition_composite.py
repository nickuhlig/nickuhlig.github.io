"""
The composite nutrition database: which source food each master ingredient's nutrition comes
from, and the per-100 g values of those foods, in one library file next to the master.

    <library>/nutrition_foods.json
      "meta":        build date, source citations
      "ingredients": {"88": {"ref": "sr:173468", "note": null, "flag": false}, ...}
                     master ingredient id -> chosen source food (reviewed by the user);
                     "removed_when_whole": true marks whole spices that are removed before eating
                     (bay leaves, cinnamon sticks): a counted/whole line is zero, a measured one counts
      "composites":  {"recipe:simple-syrup": {"name": "...", "parts": [{"ref": "sr:169655", "grams": 100}, ...]}}
                     foods built from other foods, for mixtures no source has
      "foods":       {"sr:173468": {name, source, tier, per_100g, quality, portions}, ...}
                     regenerated by `build` from the sources; never edited by hand
      "corrections": {"branded:2456621": {"sodium": null, "note": "..."}, ...}
                     reviewed fixes to a source food's values, applied by `build`; null drops a field
                     (e.g. a label's impossible sodium), a number replaces it
      "measures":    {"188": {"small bunch": 40, "bunch": 65}, "257": {"density": 1.01}, ...}
                     reviewed gram weights per ingredient for units the source portions lack
                     (recipe_nutrition.py checks these first); "item" = one medium piece,
                     "inch" = per inch, "density" = g per mL

Kept separate from ingredient_master.json on purpose: the weekly refresh rewrites the master, and
nutrition choices must not depend on that code preserving extra keys.

TIERS (the priority agreed with the user; a lower tier is preferred when choosing a ref):
    0 none:removed (removed before eating; counts as zero)
    1 sr (USDA SR Legacy)  2 cnf / frida  3 on (OpenNutrition, all values "estimated")
    4 branded (a USDA Branded product label) / fndds (USDA survey database)
    5 recipe (composite of better-tier foods)  6 fallback

COMMANDS
    python nutrition_composite.py assign-approved <approved.json>   SR matches from the review files
    python nutrition_composite.py assign-picks <picks.json>   reviewed {"picks": {id: [ref, note]}, "composites": {...}};
                                                              a note containing "FLAG" marks a stand-in
    python nutrition_composite.py set <ingredient id> <ref> [--note ...] [--flag]
    python nutrition_composite.py composite <recipe:slug> "<name>" <ref>=<grams> [<ref>=<grams> ...]
    python nutrition_composite.py measures-approved <measures.json>     merge reviewed gram weights
    python nutrition_composite.py build                                 (re)generate "foods"
    python nutrition_composite.py report
"""

import argparse
import json
import re
import sys
from collections import Counter
from datetime import date
from pathlib import Path

import nutrition_sources as ns
from library_paths import DEFAULT_LIBRARY_DIR

FILENAME = "nutrition_foods.json"
TIERS = {"none": 0, "sr": 1, "cnf": 2, "frida": 2, "on": 3, "branded": 4, "fndds": 4, "recipe": 5, "fallback": 6}
# "none:removed" -- the ingredient is removed before eating (bouquet garni, corn husks, steeped tea
# leaves): no source food, counted as zero by recipe_nutrition.py (user rule)
NO_FOOD = "none"
CITATIONS = [
    "USDA FoodData Central, SR Legacy (2018). Public domain.",
    "Health Canada, Canadian Nutrient File 2015. Open Government Licence - Canada.",
    "© Food Data (http://frida.fooddata.dk), version 5.5, November 2025. National Food Institute, "
    "Technical University of Denmark. CC BY 4.0.",
    "OpenNutrition (https://www.opennutrition.app), dataset 2025.1. ODbL 1.0.",
    "USDA FoodData Central, Branded Foods and FNDDS. Public domain.",
]


def path_for(library_dir: Path) -> Path:
    return library_dir / FILENAME


def load_db(library_dir: Path) -> dict:
    path = path_for(library_dir)
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {"meta": {}, "ingredients": {}, "composites": {}, "foods": {}, "measures": {}}


def save_db(db: dict, library_dir: Path) -> None:
    db["meta"] = {"built": date.today().isoformat(), "sources": CITATIONS,
                  "fields": ns.FIELDS, "quality_tags": ns.QUALITY_ORDER}
    # sorted keys so a rebuild that changes nothing produces an identical file
    for section in ("ingredients", "composites", "foods", "measures", "corrections"):
        db[section] = dict(sorted(db.get(section, {}).items(), key=lambda kv: (len(kv[0]), kv[0])))
    path_for(library_dir).write_text(json.dumps(db, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def source_of(ref: str) -> str:
    return ref.split(":", 1)[0]


def records_for(refs) -> dict:
    """Normalized source records for refs (excluding composites), loading each source once."""
    by_source = {}
    for ref in refs:
        by_source.setdefault(source_of(ref), set()).add(ref)
    out = {}
    for source, wanted in by_source.items():
        if source in ("sr", "branded", "fndds"):
            out.update(ns.fdc_records([int(r.split(":", 1)[1]) for r in wanted], source))
        elif source in ("cnf", "frida", "on"):
            recs = ns.load(source)
            missing = wanted - recs.keys()
            if missing:
                raise SystemExit(f"unknown {source} refs: {sorted(missing)}")
            out.update({r: recs[r] for r in wanted})
        elif source not in ("recipe", NO_FOOD):
            raise SystemExit(f"unknown source in refs: {source}")
    return out


def build_composite(definition: dict, parts: dict) -> dict:
    """Weighted per-100 g values of a mixture. A field is kept when any part reports it (parts
    that don't are counted as 0, as SR often omits true zeros); every value is 'calculated'."""
    total = sum(p["grams"] for p in definition["parts"])
    per_100g = {}
    for field in ns.FIELDS:
        if any(field in parts[p["ref"]]["per_100g"] for p in definition["parts"]):
            # sum(per-100 g value * grams / 100) is the mixture's amount; scale it to 100 g of mixture
            per_100g[field] = round(sum(parts[p["ref"]]["per_100g"].get(field, 0.0) * p["grams"]
                                        for p in definition["parts"]) / total, 4)
    return {"per_100g": per_100g, "quality": {f: "calculated" for f in per_100g}, "portions": []}


def cmd_build(db: dict) -> None:
    refs = {a["ref"] for a in db["ingredients"].values()}
    for definition in db["composites"].values():
        refs |= {p["ref"] for p in definition["parts"]}
    missing = {r for r in refs if source_of(r) == "recipe" and r not in db["composites"]}
    if missing:
        raise SystemExit(f"composites used but not defined: {sorted(missing)}")
    records = records_for(r for r in refs if source_of(r) not in ("recipe", NO_FOOD))
    foods = {}
    for ref, rec in records.items():
        per_100g, quality = dict(rec["per_100g"]), dict(rec["quality"])
        for field, value in db.get("corrections", {}).get(ref, {}).items():
            if field == "note":
                continue
            if value is None:
                per_100g.pop(field, None)
                quality.pop(field, None)
            else:
                per_100g[field], quality[field] = value, "corrected"
        foods[ref] = {"name": rec["name"], "source": rec["source"], "tier": TIERS[rec["source"]],
                      "per_100g": per_100g, "quality": quality, "portions": rec["portions"]}
    for ref, definition in db["composites"].items():
        foods[ref] = {"name": definition["name"], "source": "recipe", "tier": TIERS["recipe"],
                      "parts": definition["parts"], **build_composite(definition, records)}
    db["foods"] = foods
    print(f"built {len(foods)} foods for {len(db['ingredients'])} ingredients", file=sys.stderr)


def cmd_report(db: dict) -> None:
    tiers = Counter(TIERS[source_of(a["ref"])] for a in db["ingredients"].values())
    print("ingredients by tier:", dict(sorted(tiers.items())))
    print("flagged:", sum(1 for a in db["ingredients"].values() if a.get("flag")))
    complete = Counter(len(f["per_100g"]) for f in db["foods"].values())
    print("foods:", len(db["foods"]), "| fields per food (count: foods):", dict(sorted(complete.items())))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--recipes-dir", default=str(DEFAULT_LIBRARY_DIR))
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("assign-approved"); p.add_argument("approved")
    p = sub.add_parser("measures-approved"); p.add_argument("measures")
    p = sub.add_parser("assign-picks"); p.add_argument("picks")
    p = sub.add_parser("set"); p.add_argument("ingredient_id"); p.add_argument("ref")
    p.add_argument("--note"); p.add_argument("--flag", action="store_true")
    p = sub.add_parser("composite"); p.add_argument("ref"); p.add_argument("name"); p.add_argument("parts", nargs="+")
    sub.add_parser("build"); sub.add_parser("report")
    args = parser.parse_args()

    library_dir = Path(args.recipes_dir)
    db = load_db(library_dir)
    if args.cmd == "assign-approved":
        approved = json.loads(Path(args.approved).read_text(encoding="utf-8"))
        for ing_id, a in approved.items():
            db["ingredients"][ing_id] = {"ref": f"sr:{a['fdc_id']}", "note": a.get("note"), "flag": bool(a.get("flag"))}
        print(f"assigned {len(approved)} SR matches", file=sys.stderr)
    elif args.cmd == "assign-picks":
        data = json.loads(Path(args.picks).read_text(encoding="utf-8"))
        for ing_id, (ref, note) in data["picks"].items():
            db["ingredients"][ing_id] = {"ref": ref, "note": re.sub(r"\s*->\s*FLAG$", "", note) or None,
                                         "flag": "FLAG" in note}
        for ing_id in data.get("removed_when_whole", []):
            db["ingredients"][ing_id]["removed_when_whole"] = True
        for ref, (name, parts) in data.get("composites", {}).items():
            db["composites"][ref] = {"name": name, "parts": [{"ref": r, "grams": g} for r, g in parts.items()]}
        print(f"assigned {len(data['picks'])} ingredients", file=sys.stderr)
    elif args.cmd == "measures-approved":
        approved = json.loads(Path(args.measures).read_text(encoding="utf-8"))
        db.setdefault("measures", {})
        for ing_id, units in approved.items():
            db["measures"].setdefault(ing_id, {}).update(units)
        print(f"merged measures for {len(approved)} ingredients", file=sys.stderr)
        save_db(db, library_dir)
        return
    elif args.cmd == "set":
        db["ingredients"][args.ingredient_id] = {"ref": args.ref, "note": args.note, "flag": args.flag}
    elif args.cmd == "composite":
        if not args.ref.startswith("recipe:"):
            raise SystemExit("composite refs start with recipe:")
        parts = [{"ref": p.rsplit("=", 1)[0], "grams": float(p.rsplit("=", 1)[1])} for p in args.parts]
        db["composites"][args.ref] = {"name": args.name, "parts": parts}
    elif args.cmd == "report":
        cmd_report(db)
        return
    if args.cmd in ("build", "assign-approved", "assign-picks", "set", "composite"):
        cmd_build(db)
    save_db(db, library_dir)


if __name__ == "__main__":
    main()
